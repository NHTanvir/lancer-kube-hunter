use crate::types::Finding;

/// Render findings as a Markdown bug-bounty report snippet.
pub fn render(findings: &[Finding]) -> String {
    let mut out = String::new();
    out.push_str("# kube-hunter Findings\n\n");
    out.push_str(&format!("_Generated by lancer-kube-hunter v{}_\n\n", env!("CARGO_PKG_VERSION")));

    if findings.is_empty() {
        out.push_str("No vulnerabilities were found.\n");
        return out;
    }

    // Summary table.
    out.push_str(&format!("**{} finding(s)**\n\n", findings.len()));
    out.push_str("| Severity | ID | CVE | Category | Location | Title |\n");
    out.push_str("|----------|----|-----|----------|----------|-------|\n");
    let mut sorted: Vec<&Finding> = findings.iter().collect();
    sorted.sort_by(|a, b| b.severity.rank().cmp(&a.severity.rank()));
    for f in &sorted {
        let loc = f.port.map(|p| format!("{}:{}", f.host, p)).unwrap_or_else(|| f.host.clone());
        out.push_str(&format!(
            "| {} | {} | {} | {} | `{}` | {} |\n",
            f.severity,
            f.vid,
            f.cve.clone().unwrap_or_else(|| "-".into()),
            f.category,
            loc,
            f.name,
        ));
    }
    out.push('\n');

    // Per-finding detail.
    out.push_str("## Details\n\n");
    for f in &sorted {
        let loc = f.port.map(|p| format!("{}:{}", f.host, p)).unwrap_or_else(|| f.host.clone());
        out.push_str(&format!("### {} — {} ({})\n\n", f.vid, f.name, f.severity));
        if let Some(cve) = &f.cve {
            out.push_str(&format!("- **CVE:** {cve}\n"));
        }
        out.push_str(&format!("- **MITRE ATT&CK:** {}\n", f.category));
        out.push_str(&format!("- **Location:** `{loc}`\n"));
        out.push_str(&format!("- **Hunter:** {}\n\n", f.hunter));
        out.push_str(&format!("{}\n\n", f.description));
        if let Some(ev) = &f.evidence {
            out.push_str(&format!("**Evidence:**\n\n```\n{ev}\n```\n\n"));
        }
    }
    out
}
